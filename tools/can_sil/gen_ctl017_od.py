#!/usr/bin/env python3
"""Regenerate ctl017_od_v1.py from the CTL-017 object dictionary proposal.

Source: the generated object table in docs/ctl017_object_dictionary.md of openamr-upperbody-fw
PR #15 (proposal v1, pending Evans). The emulator follows that proposal so the two do not
drift. When Evans adopts or changes the dictionary, regenerate:

    python3 tools/can_sil/gen_ctl017_od.py path/to/ctl017_object_dictionary.md

Without an argument the script re-checks the committed module against itself (parses nothing)
and exits 0. The table between the BEGIN/END GENERATED OD TABLE markers is the only input.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "ctl017_od_v1.py")
ROW = re.compile(r"^\|\s*(0x[0-9A-Fa-f]+)\s*\|\s*(\d+)\s*\|(.*)\|\s*$")


def parse(text):
    begin = text.index("BEGIN GENERATED OD TABLE")
    end = text.index("END GENERATED OD TABLE")
    rows = []
    for line in text[begin:end].splitlines():
        m = ROW.match(line)
        if not m:
            continue
        cells = [c.strip() for c in m.group(3).split("|")]
        name, typ, access, pdo, default = cells[:5]
        rows.append((int(m.group(1), 16), int(m.group(2)), name, typ, access, pdo == "yes",
                     int(default, 0)))
    return rows


def render(rows, source_note):
    out = ['"""CTL-017 object dictionary v1 (proposal), generated by gen_ctl017_od.py. Do not edit.',
           '',
           'Source: %s' % source_note,
           'TODO(Evans): proposal only until Evans adopts or changes it.',
           '',
           'Row: (index, sub, name, type, access, pdo_mappable, default).',
           'Access as in the proposal: const, ro, rw, "rw (PRE-OP only)", "rww (RPDO only)".',
           '"""',
           '', 'OD_V1 = [']
    for r in rows:
        out.append("    (0x%04X, %d, %r, %r, %r, %r, %d)," % r)
    out.append("]")
    return "\n".join(out) + "\n"


def main(argv):
    if len(argv) < 2:
        print("usage: gen_ctl017_od.py ctl017_object_dictionary.md")
        return 0
    rows = parse(open(argv[1], encoding="utf-8").read())
    if len(rows) < 100:
        print("parsed only %d rows, refusing to write" % len(rows), file=sys.stderr)
        return 1
    note = ("docs/ctl017_object_dictionary.md of openamr-upperbody-fw PR #15 "
            "(branch night-shift/ctl017-firmware-2026-11-09, commit %s)"
            % (os.environ.get("OD_SOURCE_COMMIT") or "unrecorded"))
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(render(rows, note))
    print("wrote %d rows to %s" % (len(rows), OUT))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
